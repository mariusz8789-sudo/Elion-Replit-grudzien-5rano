/** 'lewa' | 'prawa' | null from the original English name. */
export function anatomySideOf(name: string): 'lewa' | 'prawa' | null {
  if (name.startsWith('Left ') || name.includes(' of left ')) return 'lewa';
  if (name.startsWith('Right ') || name.includes(' of right ')) return 'prawa';
  return null;
}

/** The side-free base name used as the dictionary key. */
export function anatomyBaseName(name: string): string {
  return name.replace(/^(Left|Right) /, '').replace(/ of (left|right) /g, ' of ');
}

/** Polish name for an atlas structure; falls back to the English name when missing. */
export function anatomyNamePl(name: string): string {
  return ANATOMY_NAMES_PL[anatomyBaseName(name)] ?? name;
}

/** Polish one-line role of an atlas structure, or null when none is written. */
export function anatomyRolePl(name: string): string | null {
  return ANATOMY_ROLE_PL[anatomyBaseName(name)] ?? null;
}
